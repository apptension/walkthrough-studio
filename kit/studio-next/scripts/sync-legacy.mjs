#!/usr/bin/env node
/**
 * Pull the legacy desk's design assets into studio-next.
 *
 * The stylesheet, the icon bodies and the language table are the legacy desk's
 * own source of truth; studio-next renders the same markup against them, so
 * they are copied rather than re-authored. Re-run this after the legacy desk
 * changes them — `src/test/parity/parity.test.ts` fails until you do.
 *
 *   node scripts/sync-legacy.mjs
 */
import { copyFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const LEGACY = join(ROOT, '..', 'studio');

copyFileSync(join(LEGACY, 'styles.css'), join(ROOT, 'src/styles/studio.css'));

const icons = await import(pathToFileURL(join(LEGACY, 'icons.js')).href);
const banner = '/* Generated by scripts/sync-legacy.mjs from kit/studio — do not edit. */\n';
writeFileSync(
  join(ROOT, 'src/ui/icons.gen.ts'),
  `${banner}/* eslint-disable */\n` +
    `export const ICON_BODY: Record<string, string> = ${JSON.stringify(icons.ICON_BODY, null, 2)};\n\n` +
    `export interface IconMeta {\n  viewBox: string;\n  present?: Record<string, string>;\n}\n\n` +
    `export const ICON_META: Record<string, IconMeta> = ${JSON.stringify(
      Object.fromEntries(
        Object.entries(icons.ICON_META).map(([id, meta]) => [
          id,
          { viewBox: meta.viewBox, present: meta.present ?? {} },
        ]),
      ),
      null,
      2,
    )};\n\n` +
    `export const ICON_ALIAS: Record<string, string> = ${JSON.stringify(icons.ALIAS, null, 2)};\n`,
);

process.stdout.write('synced styles.css and icons from kit/studio\n');
