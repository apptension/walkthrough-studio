#!/usr/bin/env node
/**
 * Build icons.svg (sprite) + icons.gen.js from icons/ SVG files.
 * Source of truth is the .svg files. Run: node studio/icons/build.mjs
 *
 * Presentation attrs on each source <svg> (fill/stroke/…) are copied onto the
 * <symbol> so external <use> and inlined markup both paint correctly.
 */
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(fileURLToPath(import.meta.url));
const STUDIO = dirname(ROOT);

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (name.endsWith('.svg')) out.push(p);
  }
  return out;
}

function attr(attrs, name) {
  const m = new RegExp(`\\b${name}="([^"]*)"`, 'i').exec(attrs);
  return m ? m[1] : null;
}

function parseSvg(raw) {
  const text = raw.replace(/^\uFEFF/, '').trim();
  const open = text.match(/^<svg\b([^>]*)>/i);
  if (!open) throw new Error('missing <svg>');
  const attrs = open[1];
  const viewBox = attr(attrs, 'viewBox') || '0 0 24 24';
  const body = text.replace(/^<svg\b[^>]*>/i, '').replace(/<\/svg>\s*$/i, '').trim();
  const present = {};
  for (const key of ['fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin', 'class']) {
    const v = attr(attrs, key);
    if (v != null) present[key] = v;
  }
  return { viewBox, body, present };
}

function idFromPath(file) {
  const rel = relative(ROOT, file).replace(/\\/g, '/').replace(/\.svg$/, '');
  return rel.replace(/\//g, '-');
}

function presentAttrString(present) {
  return ['fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin', 'class']
    .filter((k) => present[k] != null)
    .map((k) => ` ${k}="${present[k]}"`)
    .join('');
}

const files = walk(ROOT);
const entries = [];

for (const file of files.sort()) {
  const id = idFromPath(file);
  const { viewBox, body, present } = parseSvg(readFileSync(file, 'utf8'));
  entries.push({ id, file: relative(ROOT, file).replace(/\\/g, '/'), viewBox, body, present });
}

const sprite = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" style="display:none">
${entries
  .map((e) => {
    const attrs = presentAttrString(e.present);
    return `  <symbol id="${e.id}" viewBox="${e.viewBox}"${attrs}>\n    ${e.body.replace(/\n/g, '\n    ')}\n  </symbol>`;
  })
  .join('\n')}
</svg>
`;

writeFileSync(join(STUDIO, 'icons.svg'), sprite);

const gen = `/* Generated by icons/build.mjs — do not edit. Source: icons/ SVG files. */
export const ICON_META = ${JSON.stringify(
  Object.fromEntries(
    entries.map((e) => [e.id, { viewBox: e.viewBox, file: e.file, present: e.present }])
  ),
  null,
  2
)};

export const ICON_BODY = {
${entries.map((e) => `  ${JSON.stringify(e.id)}: ${JSON.stringify(e.body)},`).join('\n')}
};
`;

writeFileSync(join(STUDIO, 'icons.gen.js'), gen);

/** Rewrite index.html <use href="/icons.svg#id"> into inlined SVGs (currentColor-safe). */
function inlineHtmlUses() {
  const htmlPath = join(STUDIO, 'index.html');
  let html = readFileSync(htmlPath, 'utf8');
  const byId = Object.fromEntries(entries.map((e) => [e.id, e]));
  let n = 0;
  html = html.replace(/<svg\b([^>]*)>\s*<use\b[^>]*href="\/icons\.svg#([^"]+)"[^>]*\/>\s*<\/svg>/g, (full, svgAttrs, id) => {
    const e = byId[id];
    if (!e) {
      console.warn('missing icon for use:', id);
      return full;
    }
    n++;
    // Keep caller attrs (class, width, height, hidden, data-*) but drop bare viewBox if we set ours.
    let attrs = svgAttrs.trim();
    if (!/\bviewBox=/.test(attrs)) attrs = `viewBox="${e.viewBox}" ${attrs}`;
    const present = presentAttrString(e.present);
    // Avoid duplicating fill/stroke if already on the host
    const hostHas = (k) => new RegExp(`\\b${k}=`).test(attrs);
    const extra = ['fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin']
      .filter((k) => e.present[k] != null && !hostHas(k))
      .map((k) => ` ${k}="${e.present[k]}"`)
      .join('');
    return `<svg ${attrs}${extra}>${e.body}</svg>`;
  });
  // Also catch <use></use> form
  html = html.replace(/<svg\b([^>]*)>\s*<use\b[^>]*href="\/icons\.svg#([^"]+)"[^>]*>\s*<\/use>\s*<\/svg>/g, (full, svgAttrs, id) => {
    const e = byId[id];
    if (!e) return full;
    n++;
    let attrs = svgAttrs.trim();
    if (!/\bviewBox=/.test(attrs)) attrs = `viewBox="${e.viewBox}" ${attrs}`;
    const hostHas = (k) => new RegExp(`\\b${k}=`).test(attrs);
    const extra = ['fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin']
      .filter((k) => e.present[k] != null && !hostHas(k))
      .map((k) => ` ${k}="${e.present[k]}"`)
      .join('');
    return `<svg ${attrs}${extra}>${e.body}</svg>`;
  });
  writeFileSync(htmlPath, html);
  console.log(`icons: inlined ${n} <use> embeds in index.html`);
}

inlineHtmlUses();
console.log(`icons: ${entries.length} symbols → icons.svg + icons.gen.js`);
